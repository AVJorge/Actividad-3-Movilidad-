# Prueba automatizada del material. Uso: python tests/test_page.py RUTA_DE_LA_CARPETA
import sys, re
from playwright.sync_api import sync_playwright
import os, tempfile
root = sys.argv[1]
shots = sys.argv[2] if len(sys.argv) > 2 else tempfile.mkdtemp()
errors, fails = [], []
def check(cond, msg):
    (print("OK  ", msg) if cond else (fails.append(msg), print("FAIL", msg)))
with sync_playwright() as p:
    import os
    exe = os.environ.get("CHROME_PATH")
    b = p.chromium.launch(executable_path=exe) if exe else p.chromium.launch()
    for vw in [(1280,900),(390,844)]:
        pg = b.new_page(viewport={"width":vw[0],"height":vw[1]})
        pg.on("pageerror", lambda e: errors.append(str(e)))
        pg.on("console", lambda m: m.type=="error" and "fonts" not in m.text and errors.append(m.text))
        pg.goto(f"file://{root}/index.html"); pg.wait_for_timeout(300)
        print(f"--- viewport {vw}")
        # tienda
        for _ in range(12): pg.click("#sNext")
        check(pg.is_disabled("#sNext"), "tienda se detiene en 12 meses")
        ok = float(pg.text_content("#sOk").replace('\xa0',''))
        exp = 100
        for _ in range(12): exp = exp*0.95+10
        check(abs(ok-round(exp,1))<0.051, f"inventario real correcto ({ok} vs {exp:.2f})")
        check(pg.text_content("#sBad").replace('\xa0','')=="220", "inventario inflado = 220")
        pg.click("#sReset"); check(pg.text_content("#sOk")=="100" and not pg.is_disabled("#sNext"), "reinicio tienda")
        # simulador
        check(pg.locator("#tBody tr").count()==0, "tabla vacía al inicio")
        pg.click("#tNext"); pg.click("#tNext")
        rows = pg.locator("#tBody tr")
        check(rows.count()==2, "dos años calculados")
        cell = lambda r,c: int(rows.nth(r).locator("td").nth(c).text_content().replace('\xa0','').replace('$',''))
        P0=12000; s0=P0*0.03; P1=P0-s0+800
        check(cell(0,1)==P0 and cell(0,2)==round(s0) and cell(0,4)==round(P1), "año 0 correcto")
        check(cell(1,1)==round(P1), "inicio año 1 = final año 0")
        check(cell(0,5)==round(P0*0.02) and cell(0,6)==P0*11000, "internacionales y monto año 0")
        acc = int(pg.text_content("#tAcc").replace('\xa0',''))
        check(acc==round(s0+P1*0.03), "acumulado años 0-1")
        pg.click("#tAll"); check(rows.count()==7 and pg.is_disabled("#tNext"), "tabla completa 0-6")
        for k in ["tot","int","out","acc"]:
            pg.click(f"#cTabs button[data-k={k}]")
            svg = pg.inner_html("#chart")
            check(("NaN" not in svg) and ("<polyline" in svg or "<rect" in svg), f"gráfica {k} sin NaN")
        # bordes de sliders: población que decrece y constante
        pg.fill("#iP","15000"); pg.dispatch_event("#iP","input")
        pg.fill("#iC","200"); pg.dispatch_event("#iC","input")
        pg.fill("#iR","4"); pg.dispatch_event("#iR","input")
        check("disminuye" in pg.text_content("#tExplain"), "aviso de población decreciente")
        pg.fill("#iP","8000"); pg.dispatch_event("#iP","input")
        pg.fill("#iR","2.5"); pg.dispatch_event("#iR","input")
        check("mantiene" in pg.text_content("#tExplain"), "aviso de población constante")
        pg.click("#cTabs button[data-k=tot]")
        check("NaN" not in pg.inner_html("#chart") and "Infinity" not in pg.inner_html("#chart"), "gráfica constante sin NaN")
        # límites: no se pueden capturar datos de Tijuana
        pg.evaluate("()=>{const i=document.getElementById('iP');i.value='29000';i.dispatchEvent(new Event('input'))}")
        check(pg.input_value("#iP")=="15000", "slider no acepta 29 000")
        check(pg.text_content("#vR").strip().replace('\xa0',' ')=="2.5 %", "porcentaje con punto decimal")
        pg.click("#tReset"); check(rows.count()==0, "reinicio simulador")
        # excel
        pg.click(".sheet td.f >> text='=E9'")
        check("anterior" in pg.text_content("#fexp"), "explicación fórmula =E9")
        n_f = pg.locator(".sheet td.f").count()
        empty = pg.evaluate("""()=>[...document.querySelectorAll('.sheet td.f')].filter(td=>{td.click();return !document.getElementById('fexp').textContent}).map(t=>t.textContent)""")
        check(not empty, f"las {n_f} fórmulas tienen explicación {empty}")
        # quiz
        pg.locator("#quiz .q").nth(0).locator("button").nth(1).click()
        check("Correcto" in pg.locator("#quiz .q .fb").nth(0).text_content(), "quiz respuesta correcta")
        pg.locator("#quiz .q").nth(1).locator("button").nth(0).click()
        check("Intenta" in pg.locator("#quiz .q .fb").nth(1).text_content(), "quiz respuesta incorrecta")
        # checklist
        for c in pg.locator("#check input").all(): c.check()
        check("Listo" in pg.text_content("#ptext"), "lista completa")
        # desbordamiento horizontal
        ov = pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
        check(ov<=1, f"sin desbordamiento horizontal ({ov}px)")
        pg.screenshot(path=f"{shots}/ai3_{vw[0]}.png", full_page=True)

        # ===== Actividad 4 =====
        txt = lambda sel: pg.text_content(sel).replace('\xa0',' ').replace('−','-').strip()
        check(pg.is_visible("#act3") and not pg.is_visible("#act4"), "AI3 visible por defecto")
        pg.click("#sw-ai4"); pg.wait_for_timeout(100)
        check(pg.is_visible("#act4") and not pg.is_visible("#act3"), "selector muestra AI4")
        check(pg.get_attribute("#sw-ai4","aria-current")=="page" and pg.get_attribute("#sw-ai3","aria-current") is None, "pestaña AI4 marcada")
        check(txt("#bSaldo")=="-$2 050", f"saldo original negativo ({txt('#bSaldo')})")
        check("negativo" in txt("#bMsg") and "Sin excedente" in txt("#dMsg"), "mensajes de saldo negativo")
        check("Sin capacidad" in txt("#cmpCap"), "comparador sin capacidad de pago")
        pg.click("#bAdjust")
        check(txt("#bSaldo")=="$1 450", f"saldo ajustado ({txt('#bSaldo')})")
        check(pg.locator("#bOut tr.changed").count()==6, "6 gastos ajustados resaltados")
        check(txt("#mA")=="$580" and txt("#mC")=="$435" and txt("#mI")=="$435", "reparto 40/30/30")
        pg.click("#dPresets button[data-p='50,25,25']")
        check(txt("#mC")=="$363", f"reparto 50/25/25 ({txt('#mC')})")
        pg.fill("#dA","50"); pg.fill("#dC","30"); pg.fill("#dI","30")
        check("Suman 110" in txt("#dMsg"), "aviso de porcentajes que no suman 100")
        check(pg.get_attribute("#dPresets button[data-p='custom']","class").find("on")>=0, "personalizado se activa al editar")
        pg.click("#dPresets button[data-p='40,30,30']")
        # interés simple
        cm = lambda r,c: float(pg.locator("#cmpBody tr").nth(r).locator("td").nth(c).text_content().replace('\xa0','').replace('$',''))
        check(abs(cm(1,6)-9996)<0.01 and abs(cm(0,6)-9920)<0.01, f"totales simples ({cm(0,6)}, {cm(1,6)})")
        check("Tienda X" in pg.locator("#cmpBody tr").nth(0).text_content(), "fila tienda X")
        check("9 796.00" in txt("#optMix") and "124.00" in txt("#optMix"), f"compra combinada ({txt('#optMix')[:80]})")
        check("9 920.00" in txt("#optStore"), "mejor tienda con interés simple")
        check("$7 000" in txt("#optCash") and "No cabe" in txt("#cmpCap") and "7 meses" in txt("#cmpCap"), "contado y capacidad de pago")
        check(pg.locator("#cmpBody td.over").count()==3, "mensualidades que rebasan en rojo")
        check("10 880.00" in txt("#mSteps"), "ejemplo de interés simple")
        # interés compuesto (sincroniza pestañas)
        pg.click("#mTabs button[data-m=comp]")
        exp = 8000*1.02**12
        check(abs(cm(0,6)-exp)<0.01, f"total compuesto tienda X ({cm(0,6)} vs {exp:.2f})")
        check(pg.get_attribute("#xTabs button[data-m=comp]","aria-pressed")=="true", "pestañas de método sincronizadas")
        check("^$J$1" in pg.text_content("#sheet4"), "hoja muestra fórmula compuesta")
        check("11 406.09" in txt("#mSteps"), "ejemplo de interés compuesto")
        pg.select_option("#rate2","1")
        check("best" in (pg.locator("#cmpBody tr").nth(2).locator("td").nth(6).get_attribute("class") or ""), "cambiar tasa recalcula el mejor total")
        empty4 = pg.evaluate("""()=>[...document.querySelectorAll('#sheet4 td.f')].filter(td=>{td.click();return !document.getElementById('fexp4').textContent}).map(t=>t.textContent)""")
        check(not empty4, f"fórmulas AI4 con explicación {empty4}")
        pg.click("#xTabs button[data-m=simple]")
        empty4 = pg.evaluate("""()=>[...document.querySelectorAll('#sheet4 td.f')].filter(td=>{td.click();return !document.getElementById('fexp4').textContent}).map(t=>t.textContent)""")
        check(not empty4 and "*(1+D2*$J$1)" in pg.text_content("#sheet4"), "fórmulas simples con explicación")
        # capacidad suficiente: tasa baja + reparto alto a crédito
        for k in range(3): pg.select_option(f"#rate{k}","1")
        pg.click("#dPresets button[data-p='custom']"); pg.fill("#dA","0"); pg.fill("#dC","100"); pg.fill("#dI","0")
        check("Cabe" in txt("#cmpCap"), "mensaje cuando la mensualidad cabe")
        pg.click("#bMine")
        check(txt("#bSaldo")=="$0" and "Escribe" in txt("#bMsg"), "modo mis datos")
        pg.fill("#in0","10000"); pg.fill("#out0","4000")
        check(txt("#bSaldo")=="$6 000", "captura propia recalcula")
        pg.click("#bReset")
        pg.locator("#quizB .q").nth(1).locator("button").nth(2).click()
        check("Correcto" in pg.locator("#quizB .fb").nth(1).text_content(), "quiz AI4")
        for c in pg.locator("#check4 input").all(): c.check()
        check("Listo" in txt("#ptext4"), "lista AI4 completa")
        ov = pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
        check(ov<=1, f"AI4 sin desbordamiento horizontal ({ov}px)")
        pg.screenshot(path=f"{shots}/ai4_{vw[0]}.png", full_page=True)

        # ===== Regresión de errores corregidos =====
        pg.goto(f"file://{root}/index.html#ai4"); pg.wait_for_timeout(200)
        pg.click("#bAdjust"); pg.click("#dPresets button[data-p='34,33,33']")
        amt = lambda s: int(txt(s).replace('$','').replace(' ',''))
        check(amt("#mA")+amt("#mC")+amt("#mI")==1450, "reparto 34/33/33 suma exactamente el excedente")
        pg.fill("#dA","33.33"); pg.fill("#dC","33.33"); pg.fill("#dI","33.34")
        check("capacidad de pago es" in txt("#dMsg"), "porcentajes con decimales que suman 100")
        check(amt("#mA")+amt("#mC")+amt("#mI")==1450, "reparto con decimales cuadra")
        pg.fill("#dI","40")
        check("Falta definir el reparto" in txt("#cmpCap"), "comparador avisa porcentajes inválidos")
        pg.fill("#dA","50"); pg.fill("#dC","0"); pg.fill("#dI","50")
        check("no destinaste" in txt("#cmpCap"), "comparador avisa crédito en 0 %")
        pg.fill("#dA","-20")
        check(pg.input_value("#dA")=="0", "porcentaje negativo se corrige a 0")
        pg.fill("#out0","-5000")
        check(pg.input_value("#out0")=="0", "gasto negativo se corrige a 0")
        pg.evaluate("location.hash='%E0%A4%A'"); pg.wait_for_timeout(150)
        pg.evaluate("location.hash='presupuesto'"); pg.wait_for_timeout(150)
        check(pg.is_visible("#act4"), "hash malformado no rompe la navegación")
        bg = pg.evaluate("getComputedStyle(document.querySelector('nav.switch')).position")
        check(bg=="static", "selector de actividades no es barra fija")
        pg.goto(f"file://{root}/index.html#ai4"); pg.wait_for_timeout(300)
        check(pg.evaluate("window.scrollY")==0 and pg.is_visible("#act4"), "enlace #ai4 abre arriba con el selector visible")
        # navegación directa por hash
        pg.goto(f"file://{root}/index.html#comparador"); pg.wait_for_timeout(200)
        check(pg.is_visible("#act4") and not pg.is_visible("#act3"), "enlace directo a sección de AI4")
        pg.goto(f"file://{root}/index.html#simulador"); pg.wait_for_timeout(200)
        check(pg.is_visible("#act3") and not pg.is_visible("#act4"), "enlace directo a sección de AI3")
        pg.close()
    b.close()
print("\nErrores JS:", errors or "ninguno")
print("Fallas:", fails or "ninguna")
sys.exit(1 if (errors or fails) else 0)
